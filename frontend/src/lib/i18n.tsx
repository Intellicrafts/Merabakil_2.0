function resolve(obj: unknown, keys: string[]): string {
  let cur = obj as Record<string, unknown>;
  for (const k of keys) {
    if (cur == null || typeof cur !== "object") return keys.join(".");
    cur = cur[k] as Record<string, unknown>;
  }
  return typeof cur === "string" ? cur : keys.join(".");
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nCtx>({
  lang: "en",
  setLang: () => undefined,
  t: (key) => key,
});

function HtmlLangSync({ lang }: { lang: Lang }) {
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  return null;
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
      if (stored === "en" || stored === "hi") setLangState(stored);
    } catch {
      // localStorage unavailable
    }
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // ignore
    }
  }, []);

  const t = useCallback(
    (key: string) => resolve(translations[lang], key.split(".")),
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      <HtmlLangSync lang={lang} />
      {children}
    </I18nContext.Provider>
  );
}

export function useTranslation() {
  return useContext(I18nContext);
}
