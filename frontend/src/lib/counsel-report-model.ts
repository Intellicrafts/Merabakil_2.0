import type { ChatMessage } from "./conversations";
import { citedSources } from "./cited-sources";

export interface CounselReportSource {
  title?: string;
  citation?: string;
  url?: string;
}

export interface CounselReportPayload {
  question: string;
  answer: string;
  sources?: CounselReportSource[];
  disclaimer?: string;
}

/** One question/answer exchange in a full-conversation report. */
export interface CounselReportTurn {
  question: string;
  answer: string;
  sources?: CounselReportSource[];
}

/** A full Saarthi conversation rendered as a single counsel report. */
export interface ConversationReportPayload {
  title?: string;
  turns: CounselReportTurn[];
  disclaimer?: string;
}

const CITATION_MARK = /\[(?:KB|WEB)-\d+\]/g;

export function stripCitationMarkers(text: string): string {
  return text.replace(CITATION_MARK, "").replace(/\n{3,}/g, "\n\n").trim();
}

export function reportStamp(date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}${m}${d}`;
}

export function counselReportFilename(date = new Date()): string {
  return `Saarthi-Counsel-Report-${reportStamp(date)}.pdf`;
}

export function conversationReportFilename(date = new Date()): string {
  return `Saarthi-Conversation-Report-${reportStamp(date)}.pdf`;
}

/**
 * A short, human-readable document reference for the report masthead, e.g.
 * `SCR-20261021-4F9Q`. Deterministic for a given timestamp so the same report
 * carries the same id.
 */
export function reportReference(date = new Date(), prefix = "SCR"): string {
  const secondOfDay = date.getHours() * 3600 + date.getMinutes() * 60 + date.getSeconds();
  const tail = secondOfDay.toString(36).toUpperCase().padStart(4, "0").slice(-4);
  return `${prefix}-${reportStamp(date)}-${tail}`;
}

/**
 * Build a full-conversation report payload from chat messages. Each assistant
 * answer is paired with the preceding user question (the same pairing the chat
 * UI uses), its real cited sources, and the shared disclaimer. Empty/streaming
 * answers are skipped.
 */
export function buildConversationPayload(messages: ChatMessage[]): ConversationReportPayload {
  const turns: CounselReportTurn[] = [];
  let lastUser = "";
  let disclaimer: string | undefined;

  for (const msg of messages) {
    if (msg.role === "user") {
      const text = msg.content?.trim();
      if (text) lastUser = text;
      continue;
    }
    if (msg.role !== "assistant") continue;

    const research = msg.research;
    const answer = (msg.content || research?.answer || "").trim();
    if (!answer) continue;

    let sources: CounselReportSource[] = [];
    if (research) {
      const cited = citedSources(research);
      sources = [
        ...cited.kb.map(({ source }) => ({
          title: source.title ?? undefined,
          citation: source.citation ?? undefined,
        })),
        ...cited.web.map(({ source }) => ({ title: source.title, url: source.url })),
      ];
      if (!disclaimer && research.disclaimer?.trim()) disclaimer = research.disclaimer.trim();
    }

    turns.push({
      question: (lastUser || research?.query || "").trim(),
      answer,
      sources,
    });
    lastUser = "";
  }

  return { turns, disclaimer };
}

export function formatCounselReportPlaintext(payload: CounselReportPayload): string {
  const question = stripCitationMarkers(payload.question || "—");
  const answer = stripCitationMarkers(payload.answer || "");
  const sources = (payload.sources ?? []).slice(0, 12);
  const disclaimer =
    payload.disclaimer?.trim() ||
    "This response is generated by an AI system for informational purposes only and does not constitute legal advice.";

  const sourceLines = sources
    .map((src, i) => {
      const title = src.title || src.citation || src.url || `Source ${i + 1}`;
      const extra = [src.citation, src.url].filter(Boolean).join(" · ");
      return extra && extra !== title ? `${i + 1}. ${title} — ${extra}` : `${i + 1}. ${title}`;
    })
    .join("\n");

  return [
    "MeraBakil · Saarthi counsel report",
    "",
    "Your question",
    question,
    "",
    "Counsel note",
    answer,
    "",
    sources.length ? "Sources" : "",
    sourceLines,
    "",
    "Disclaimer",
    disclaimer,
  ]
    .filter((line, i, arr) => !(line === "" && arr[i - 1] === ""))
    .join("\n")
    .trim();
}

export function formatConversationReportPlaintext(payload: ConversationReportPayload): string {
  const lines: string[] = ["MeraBakil · Saarthi counsel report", ""];
  if (payload.title?.trim()) lines.push(payload.title.trim(), "");

  payload.turns.forEach((turn, i) => {
    lines.push(`${i + 1}. Question`, stripCitationMarkers(turn.question || "—"), "");
    lines.push("Counsel note", stripCitationMarkers(turn.answer || ""), "");

    const sources = (turn.sources ?? []).slice(0, 12);
    if (sources.length) {
      lines.push("Sources");
      sources.forEach((src, j) => {
        const title = src.title || src.citation || src.url || `Source ${j + 1}`;
        const extra = [src.citation, src.url].filter(Boolean).join(" · ");
        lines.push(extra && extra !== title ? `${j + 1}. ${title} — ${extra}` : `${j + 1}. ${title}`);
      });
      lines.push("");
    }
  });

  const disclaimer =
    payload.disclaimer?.trim() ||
    "This response is generated by an AI system for informational purposes only and does not constitute legal advice.";
  lines.push("Disclaimer", disclaimer);

  return lines
    .filter((line, i, arr) => !(line === "" && arr[i - 1] === ""))
    .join("\n")
    .trim();
}
